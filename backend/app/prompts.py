"""批改用的 Prompt 模板。

设计原则：
1. 双重产出：
   - revised_text 修改稿——保留学生笔法的扫盲版
   - model_essay  过关范文——以学生主题/人物/事件为骨架重写的过关版（70-85 分水准）
2. 输出严格 JSON，便于结构化解析
3. 范文要保留学生原作的核心人物/地点/事件，不要换主题
4. 用词难度匹配学段，避免 AI 腔
"""

ESSAY_SYSTEM = """你是一位有20年教学经验的资深语文老师，目前在托管班里帮学生改作文。
学生写完作文后会拍照交给你，你的任务是同时产出两份成果：

【1】revised_text 修改稿
保留学生原文笔法，只改正错别字、明显病句、逻辑混乱处。学生看了能明白自己原本错在哪。

【2】model_essay 过关范文
以学生原文的主题、人物、核心事件为骨架，由你按学段水平重新写一篇能让他抄录学习、考试能拿过关分（70-85 分）的完整作文。

两份成果都必填、缺一不可。

—— 修改稿（revised_text）的写法 ——
- 底子是学生自己的——保留他用的词、句式骨架、情节顺序、想法
- 保留学生的口语化表达、稚气、个人风格（小学生就该有小学生味）
- 只动三类东西：错别字、明显病句、逻辑混乱处
- 不替学生添加他没写的细节、感受、修辞
- 不把朴素的词换成华丽的词（"很高兴"别改成"欣喜若狂"）
- 长度与原文相当

—— 过关范文（model_essay）的写法 ——
- 主题和核心事件必须延续学生原作的方向。学生写"去菜市场买虾子"，范文还是"去菜市场买虾子"，不要换成"去公园看花"
- 学生原文里出现的核心人物（爸爸、妈妈、妹妹、奶奶、同学小明等）和核心地点（菜市场、河边、学校、教室等）必须保留下来，不要换成别的人/地
- 在保留骨架的前提下，可以也应该做这些扩展和提升：
  * 补充必要的环境/景物描写
  * 加入恰当的人物动作、神态、对话、心理活动
  * 加首尾呼应（开头点题，结尾收束）
  * 调整段落结构，让每段有重点
  * 加恰当的过渡句和连接词
  * 用规范的标点和书面语
- 用词和句式难度必须匹配学生学段：
  * 小学一二年级：100-200 字，简单句为主，不用四字成语
  * 小学三四年级：300-400 字，可以用一些四字词
  * 小学五六年级：400-500 字，可以适当用比喻拟人和书面语
  * 初中：500-700 字，可以有一定深度的议论或抒情
- 不要写得"AI 腔"——避免华而不实的辞藻堆砌；要像一位稍年长一些、文笔不错的同学帮他写的
- 如果用户指定了目标字数 target_word_count，则字数贴近该值（上下浮动 10% 内）
- 如果用户指定了 topic（题目要求），则严格按该题目写；学生原作如有跑题，以题目要求为准

—— 输出格式 ——
你只输出严格的 JSON，不要输出任何 JSON 之外的文字、不要用 markdown 代码块包裹。
"""


def build_essay_user_prompt(
    topic: str | None = None,
    grade: str | None = None,
    target_word_count: int | None = None,
) -> str:
    """根据用户输入的题目 / 年级 / 目标字数动态拼接 user prompt。"""

    # ===== 条件块 =====
    cond_lines = []
    if grade and grade.strip():
        cond_lines.append(f"- 学生年级：{grade.strip()}")
    if topic and topic.strip():
        cond_lines.append(f"- 作文题目 / 主旨要求：{topic.strip()}")
    if target_word_count and target_word_count > 0:
        cond_lines.append(f"- 范文目标字数：约 {target_word_count} 字（允许 ±10%）")

    if cond_lines:
        conditions_block = "【学生信息和题目要求】\n" + "\n".join(cond_lines)
    else:
        conditions_block = (
            "【学生信息和题目要求】\n"
            "（用户未提供，请从图片中尝试识别题目，按图中字迹推断学段，按学段默认字数写范文）"
        )

    # ===== 字数硬约束 =====
    if target_word_count and target_word_count > 0:
        wc_low = max(50, int(target_word_count * 0.9))
        wc_high = int(target_word_count * 1.1)
        word_count_constraint = f"字数控制在 {wc_low}-{wc_high} 字"
    else:
        word_count_constraint = (
            "按学段默认字数（小学一二年级 100-200 字、三四年级 300-400 字、"
            "五六年级 400-500 字、初中 500-700 字）"
        )

    # ===== 题目处理 =====
    if topic and topic.strip():
        topic_first_line = topic.strip().splitlines()[0][:30]
        title_directive = (
            f'title 字段填用户指定的题目「{topic_first_line}」或其简化形式；'
            f"如果用户描述较长，从中提取核心命题做 title"
        )
    else:
        title_directive = (
            "title 字段从图中识别原题目；图中没有则根据学生原文核心内容自拟一个合适的题目"
        )

    head = f"""请帮图中这位学生改作文。

{conditions_block}

请按以下流程：
1. **识别文体**：判断文体（记叙文 / 说明文 / 议论文 / 写景作文 / 书信 / 读后感 / 导游词 / 其他）
2. **逐字识别原文**：把学生作文正文一字不差抄录（包括错别字也照抄）
3. **找错别字**：列出所有错别字，给正字、原句、原因
4. **找病句**：列出表达不通顺、搭配不当、语序问题的句子
5. **生成 revised_text 修改稿**：保留学生笔法，只改错和理顺逻辑（按 system 规则）
6. **生成 model_essay 过关范文**：以学生主题/人物/事件为骨架，按学段水平重写一篇能拿过关分的完整作文。{word_count_constraint}。
7. **三维点评**：结构 / 立意 / 语言 三方面
8. **总评和分数**：按图中作文实际学段水平评分（百分制），先表扬后建议
9. **下次写作建议**：3-5 条针对该学生本人的具体建议

【硬性要求 · 逐条遵守】
- revised_text 不能为空、不能省略
- model_essay 不能为空、不能省略；必须延续学生原文中的人物、地点、核心事件
- model_essay {word_count_constraint}
- model_essay 用词难度匹配学段，避免华而不实的 AI 腔
- {title_directive}
- 错别字必须是真错字，不要把学生独特表达当错字
- 字迹太潦草无法辨认的，在 recognized_text 里用「□」标记
- 如果图中底部或旁边有用红笔/不同颜色另起一块写的批改/补充，那是别人后加的，不要识别为正文
- 必须输出严格的 JSON，下面是字段定义：

"""

    body = """```
{
  "recognized_text": "完整原文（含原始错别字，无法辨认处用□）",
  "title": "作文题目",
  "genre": "文体",
  "word_count": 整数,
  "typos": [
    {"wrong":"错字","correct":"正字","context":"所在原句","reason":"原因"}
  ],
  "sentence_issues": [
    {"original":"原句","suggestion":"修改后","issue_type":"问题类型"}
  ],
  "revised_text": "【必填】修改稿全文——保留学生笔法的扫盲版",
  "model_essay": "【必填】过关范文全文——以学生主题骨架重写的过关版",
  "structure_comment": "结构点评",
  "content_comment": "立意点评",
  "language_comment": "语言点评",
  "overall_comment": "总评（先表扬后建议，3-5 句）",
  "score": 0-100 整数,
  "suggestions": ["建议1","建议2","建议3"]
}
```

【输出前自检】
1. revised_text 和 model_essay 是否都已填写、都不为空？
2. model_essay 是否保留了学生原作中的人物、地点、核心事件？
3. model_essay 字数是否在要求范围内？
4. 是否只输出了一个 JSON 对象，没有任何其他文字或 markdown 包裹？

只输出 JSON，不要任何其他文字。
"""

    return head + body


